/** Netlify-style redirect rules for static hosts (copied to dist via public/). */
import fs from 'node:fs';
import path from 'node:path';
import { PATH_REDIRECTS } from './redirects.mjs';
import { checkoutDestination, CHECKOUT_PATH_REDIRECTS, CHECKOUT_URLS } from '../src/config/checkout-redirects.mjs';
import { SUPPORT_CHANNELS } from '../src/config/outbound-redirects.mjs';
import { SITE_URL } from '../src/config/site-url.mjs';

const lines = ['# Generated by scripts/generate-static-redirects.mjs. Do not edit.'];
for (const [from, to] of PATH_REDIRECTS.entries()) {
  lines.push(`${from}  ${to}  301`);
}
// Static checkout uses generated HTML to filter the query.

const out = path.join('public', '_redirects');
fs.writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length - 1} redirect rules → ${out}`);

const robots = `User-agent: *
Allow: /
Disallow: /go/
Disallow: /es/go/
Disallow: /de/go/
Disallow: /fr/go/

Sitemap: ${SITE_URL}/sitemap.xml
`;
fs.writeFileSync(path.join('public', 'robots.txt'), robots);
console.log(`Wrote public/robots.txt → Sitemap: ${SITE_URL}/sitemap.xml`);

function escapeHtml(value) {
  return value.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

/** Fallback for hosts that serve static files without redirect middleware. */
function writeGoPage(from, { heading, description, script, destination, action, sponsored = false }) {
  const dir = path.join('public', from);
  fs.mkdirSync(dir, { recursive: true });
  const title = escapeHtml(heading);
  const rel = sponsored ? ' rel="sponsored nofollow"' : '';
  fs.writeFileSync(
    path.join(dir, 'index.html'),
    `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, follow">
<title>${title}</title>
<meta name="description" content="${escapeHtml(description)}">
<script>${script}</script>
</head>
<body>
<h1>${title}</h1>
<a href="${escapeHtml(destination)}"${rel}>${escapeHtml(action)}</a>
</body>
</html>
`,
  );
}

const GO_PRODUCT_LABELS = {
  '/go/cheats/': 'Main product',
  '/go/hwid-spoofer/': 'HWID Spoofer',
  '/go/skin-changer/': 'Skin Changer',
  '/go/cloud-dma/': 'Cloud DMA',
};

for (const [from, to] of CHECKOUT_PATH_REDIRECTS) {
  if (!from.endsWith('/')) continue;
  const lifetimeOnly = to === CHECKOUT_URLS.cloudDma;
  writeGoPage(from, {
    heading: `Purchase options for ${GO_PRODUCT_LABELS[from]}`,
    description: 'Open the product page to review available options and pricing.',
    script: `location.replace((${checkoutDestination.toString()})(${JSON.stringify(to)},location.search,${lifetimeOnly}));`,
    destination: checkoutDestination(to, '', lifetimeOnly),
    action: 'View Purchase Options',
    sponsored: true,
  });
}

for (const { path: from, destination, label } of Object.values(SUPPORT_CHANNELS)) {
  writeGoPage(from, {
    heading: label,
    description: `Continue to ${label.toLowerCase()}.`,
    script: `location.replace(${JSON.stringify(destination)});`,
    destination,
    action: 'Continue',
  });
}
console.log('Wrote checkout and support redirect pages → public/go/');
